class FixingExecutor:
    async def execute(self, task: FrozenTask, workspace: Path) -> ExecutionResult:
        target = workspace / "value.py"
        target.write_text("VALUE = 2\n", encoding="utf-8")
        return ExecutionResult(output=f"fixed {task.id}", metadata={"calls": 1, "cost": 0.01})


def _fixture(tmp_path: Path) -> Path:
    fixture = tmp_path / "fixture"
    fixture.mkdir()
    (fixture / "value.py").write_text("VALUE = 1\n", encoding="utf-8")
    (fixture / "check.py").write_text(
        "from value import VALUE\nraise SystemExit(0 if VALUE == 2 else 1)\n",
        encoding="utf-8",
    )
    return fixture


def test_load_tasks_is_strict_and_rejects_duplicate_ids(tmp_path: Path) -> None:
    fixture = _fixture(tmp_path)
    tasks_path = tmp_path / "tasks.jsonl"
    line = (
        '{"id":"fix","fixture":"fixture","prompt":"fix it",'
        '"verify":[["python","check.py"]],"tags":["python"]}\n'
    )
    tasks_path.write_text(line + line, encoding="utf-8")

    with pytest.raises(ValueError, match="duplicate task id"):
        load_tasks(tasks_path)

    tasks_path.write_text(line, encoding="utf-8")
    tasks = load_tasks(tasks_path)
    assert tasks[0].fixture == fixture.resolve()
    assert tasks[0].verify == (("python", "check.py"),)


def test_workspace_digest_ignores_runtime_caches(tmp_path: Path) -> None:
    fixture = _fixture(tmp_path)
    expected = workspace_digest(fixture)
    pycache = fixture / "__pycache__"
    pytest_cache = fixture / ".pytest_cache" / "v" / "cache"
    pycache.mkdir()
    pytest_cache.mkdir(parents=True)
    (pycache / "value.cpython-312.pyc").write_bytes(b"generated bytecode")
    (pytest_cache / "nodeids").write_text("generated metadata", encoding="utf-8")

    assert workspace_digest(fixture) == expected


@pytest.mark.anyio
async def test_evaluation_runner_creates_reproducible_trial_artifact(tmp_path: Path) -> None:
    fixture = _fixture(tmp_path)
    task = FrozenTask(
        id="fix",
        fixture=fixture,
        prompt="set VALUE to 2",
        verify=(("python", "check.py"),),
        tags=("python",),
    )
    runner = EvaluationRunner(tmp_path / "artifacts", keep_workspaces=False)

    artifact = await runner.run_trial(task, FixingExecutor(), candidate_id="candidate-a", seed=7)

    assert artifact.status == "passed"
    assert artifact.task_id == "fix"
    assert artifact.candidate_id == "candidate-a"
    assert artifact.seed == 7
    assert artifact.verifiers[0].exit_code == 0
    assert artifact.workspace_digest_before != artifact.workspace_digest_after
    assert artifact.metadata == {"calls": 1, "cost": 0.01}
    assert artifact.artifact_path is not None and artifact.artifact_path.exists()
    loaded = TrialArtifact.from_path(artifact.artifact_path)
    assert loaded == artifact
    assert not any(path.is_dir() for path in (tmp_path / "artifacts" / "workspaces").glob("*"))


def test_reducer_and_promotion_gate_use_only_trial_artifacts(tmp_path: Path) -> None:
    baseline = [
        TrialArtifact.synthetic(
            task_id=f"t{index}", candidate_id="base", passed=True, duration_ms=10 + index
        )
        for index in range(5)
    ]
    candidate = [
        TrialArtifact.synthetic(
            task_id=f"t{index}", candidate_id="next", passed=index != 4, duration_ms=8 + index
        )
        for index in range(5)
    ]

    baseline_summary = reduce_trials(baseline)
    candidate_summary = reduce_trials(candidate)
    decision = PromotionGate(min_trials=5, min_pass_rate=0.8, max_pass_rate_regression=0.2).decide(
        baseline=baseline_summary,
        candidate=candidate_summary,
    )

    assert baseline_summary.pass_rate == 1.0
    assert candidate_summary.pass_rate == 0.8
    assert candidate_summary.calls_per_passed_trial == 0.0
    assert candidate_summary.priced_trials == 0
    assert candidate_summary.cost_per_passed_trial is None
    assert decision.approved is True
    assert decision.evidence["candidate_trials"] == 5

    target = tmp_path / "SKILL.md"
    target.write_text("old\n", encoding="utf-8")
    store = CandidateStore(tmp_path / "candidates")
    pending = store.create(target=target, content="new\n", parent_id=None)
    promoted = store.promote(pending.id, decision)

    assert promoted.status == "promoted"
    assert target.read_text(encoding="utf-8") == "new\n"
    assert store.load(pending.id).status == "promoted"


def test_rejected_candidate_never_mutates_target(tmp_path: Path) -> None:
    target = tmp_path / "SKILL.md"
    target.write_text("stable\n", encoding="utf-8")
    store = CandidateStore(tmp_path / "candidates")
    candidate = store.create(target=target, content="regression\n", parent_id=None)
    baseline = reduce_trials(
        [
            TrialArtifact.synthetic(task_id=f"t{i}", candidate_id="base", passed=True)
            for i in range(3)
        ]
    )
    regressed = reduce_trials(
        [
            TrialArtifact.synthetic(task_id=f"t{i}", candidate_id="bad", passed=False)
            for i in range(3)
        ]
    )
    decision = PromotionGate(min_trials=3, min_pass_rate=0.8).decide(
        baseline=baseline,
        candidate=regressed,
    )

    rejected = store.promote(candidate.id, decision)

    assert decision.approved is False
    assert rejected.status == "rejected"
    assert target.read_text(encoding="utf-8") == "stable\n"


@pytest.mark.anyio
async def test_campaign_freezes_matrix_and_rebuilds_offline(tmp_path: Path) -> None:
    fixture = _fixture(tmp_path)
    task = FrozenTask(
        id="fix",
        fixture=fixture,
        prompt="set VALUE to 2",
        verify=(("python", "check.py"),),
    )
    root = tmp_path / "campaign"
    campaign = EvaluationCampaign(
        root,
        CampaignConfig(candidate_id="candidate-a", seeds=(7, 11), concurrency=2),
    )

    report = await campaign.run((task,), FixingExecutor())
    rebuilt = rebuild_campaign(root)
    manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))

    assert report.summary.trials == 2
    assert report.summary.pass_rate == 1.0
    assert rebuilt.summary == report.summary
    assert rebuilt.manifest_digest == report.manifest_digest
    assert rebuilt.inventory_digest == report.inventory_digest
    assert rebuilt.report_digest == report.report_digest
    assert manifest["repository"]["source_file_count"] > 0
    assert len(manifest["repository"]["source_sha256"]) == 64


@pytest.mark.anyio
async def test_campaign_rejects_tampered_trial_evidence(tmp_path: Path) -> None:
    fixture = _fixture(tmp_path)
    task = FrozenTask(
        id="fix",
        fixture=fixture,
        prompt="set VALUE to 2",
        verify=(("python", "check.py"),),
    )
    root = tmp_path / "campaign"
    campaign = EvaluationCampaign(root, CampaignConfig(candidate_id="candidate-a"))
    report = await campaign.run((task,), FixingExecutor())
    artifact_path = report.trial_artifacts[0]
    artifact_path.write_text(
        artifact_path.read_text(encoding="utf-8").replace(
            '"status": "passed"', '"status": "failed"'
        ),
        encoding="utf-8",
    )

    with pytest.raises(ValueError, match="inventory"):
        rebuild_campaign(root)
